import os
import sys
import shutil
import subprocess


# Expected artifacts from the DRP-AI Translator
EXPECTED_RESULT_FILES = [
    "addr_map.txt",
    "addr_map.yaml",
    "aimac_cmd.bin",
    "aimac_desc.bin",
    "aimac_param_cmd.bin",
    "aimac_param_desc.bin",
    "data_in_list.txt",
    "data_out_list.txt",
    "drp_config.mem",
    "drp_desc.bin",
    "drp_lib_info.txt",
    "drp_param.bin",
    "drp_param_info.txt",
    "drp_param.txt",
    "weight.bin",
]


def _translator_dir(opts):
    """
    Translator run directory, derived from drp_compiler_dir.
    """
    drp_dir = opts.get("drp_compiler_dir") or "."
    candidate = os.path.join(drp_dir, "..", "translator")
    return os.path.normpath(candidate)


def _sparse_enabled():
    """
    Interpretation of the SPARSE_ENABLE environment variable.
      - unset        : enabled
      - "true"       : enabled
      - "false", ... : disabled
    """
    val = os.environ.get("SPARSE_ENABLE")
    if val is None:
        return True
    return val.strip().lower() == "true"


def run_translator(int8_onnx_path, prepost_yaml_path, opts, output_dir):
    """
    Step2: run the Translator conversion and place the artifacts in output_dir.

    Args:
        int8_onnx_path    : INT8 ONNX generated by Step1
        prepost_yaml_path : generated Pre/Post YAML
        opts              : opts of arg_parser
        output_dir        : output directory (-o)
    """
    translator_dir = _translator_dir(opts)
    run_sh = os.path.join(translator_dir, "run_Translator_v2h.sh")

    # PREFIX is derived from the output_dir name
    prefix = os.path.basename(os.path.normpath(output_dir))
    if not prefix:
        prefix = "drpai_output"

    s_addr = opts.get("s_addr", "0x80000000")

    # run_Translator_v2h.sh has no shebang, so it is started through bash.
    cmd = [
        "bash", run_sh,
        prefix,
        "--onnx", os.path.abspath(int8_onnx_path),
        "--prepost", os.path.abspath(prepost_yaml_path),
        "--s_addr", s_addr,
    ]
    if _sparse_enabled():
        cmd.append("--sparse")

    print("-------------------------------------------------")
    print("[Step2] Run DRP-AI Translator")
    print("  translator dir : ", translator_dir)
    print("  prefix         : ", prefix)
    print("  onnx           : ", int8_onnx_path)
    print("  prepost        : ", prepost_yaml_path)
    print("  s_addr         : ", s_addr)
    print("  sparse         : ", _sparse_enabled())
    print("  command        : ", " ".join(cmd))

    # Remove existing expected files
    for f in EXPECTED_RESULT_FILES:
        try:
            os.remove(os.path.join(output_dir, f))
        except OSError:
            pass

    # run_Translator_v2h.sh calls `python3 run.py` internally, so the directory
    # of sys.executable is put at the head of PATH to use the same Python (venv)
    # as the wrapper.
    env = os.environ.copy()
    py_bindir = os.path.dirname(os.path.abspath(sys.executable))
    env["PATH"] = py_bindir + os.pathsep + env.get("PATH", "")

    ret = subprocess.run(cmd, cwd=translator_dir, env=env)
    if ret.returncode != 0:
        raise RuntimeError("[Step2] Translator failed (rc=%d)" % ret.returncode)

    # The Translator writes under output/<PREFIX>/
    gen_dir = os.path.join(translator_dir, "output", prefix)
    if not os.path.isdir(gen_dir):
        raise RuntimeError("[Step2] Translator output dir not found: " + gen_dir)

    _move_outputs(gen_dir, output_dir)
    _verify_outputs(output_dir)

    print("[Step2] DRP-AI object files placed in: ", output_dir)


def _move_outputs(gen_dir, output_dir):
    """Move output/<PREFIX>/* to output_dir."""
    os.makedirs(output_dir, exist_ok=True)
    for name in os.listdir(gen_dir):
        src = os.path.join(gen_dir, name)
        dst = os.path.join(output_dir, name)
        if os.path.exists(dst):
            if os.path.isdir(dst):
                shutil.rmtree(dst)
            else:
                os.remove(dst)
        shutil.move(src, dst)
    # Remove the now empty generation directory
    try:
        shutil.rmtree(gen_dir)
    except OSError:
        pass


def _verify_outputs(output_dir):
    """Check that the expected files exist; error if any is missing."""
    missing = []
    for f in EXPECTED_RESULT_FILES:
        if not os.path.isfile(os.path.join(output_dir, f)):
            missing.append(f)
    if missing:
        raise RuntimeError(
            "[Step2] Expected result files not found: " + ", ".join(missing)
        )